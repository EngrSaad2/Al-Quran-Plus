window.toBanglaNumber = function(num) {
    const bnNums = ['০','১','২','৩','৪','৫','৬','৭','৮','৯'];
    return String(num).split('').map(d => bnNums[parseInt(d)] !== undefined ? bnNums[parseInt(d)] : d).join('');
};

